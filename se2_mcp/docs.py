"""Schema oracle: field documentation extracted from the SDK's XML doc files.

The SDK ships ``*.xml`` documentation next to every assembly. For a definition
type such as ``PlacementDefinitionObjectBuilder`` these files carry a per-field
``<summary>`` written by the developers — which is the only authoritative
description of what a field means. Parsing ~50 MB of XML on every call is far
too slow, so members are extracted once into a small SQLite cache.
"""

from __future__ import annotations

import re
import sqlite3
import time
import xml.etree.ElementTree as ET
from typing import Any

from .config import PATHS

DOCS_SCHEMA = """
CREATE TABLE IF NOT EXISTS docs (
    member  TEXT PRIMARY KEY,   -- e.g. "F:Keen.Game2....AlignWithMountPoints"
    owner   TEXT,               -- declaring type, for grouping
    leaf    TEXT,               -- field/property name
    kind    TEXT,               -- T (type) | F (field) | P (property)
    summary TEXT
);
CREATE INDEX IF NOT EXISTS ix_docs_owner ON docs(owner);
CREATE TABLE IF NOT EXISTS docmeta (key TEXT PRIMARY KEY, value TEXT);
"""

# Members generated by the serializer or explicit interface implementations are
# noise for a modder; they never appear in a definition file.
_NOISE = re.compile(r"\.Serializer|#|\.\.ctor|\.get_|\.set_")

_WS = re.compile(r"\s+")


def _db() -> sqlite3.Connection:
    conn = sqlite3.connect(PATHS.cache_dir / "se2_docs.sqlite3")
    conn.row_factory = sqlite3.Row
    conn.executescript(DOCS_SCHEMA)
    return conn


def _text(node: ET.Element | None) -> str:
    if node is None:
        return ""
    # Doc comments contain inline tags (<see cref="..."/>); itertext flattens them.
    return _WS.sub(" ", "".join(node.itertext())).strip()


def is_built() -> bool:
    try:
        conn = _db()
        n = conn.execute("SELECT COUNT(*) n FROM docs").fetchone()["n"]
        conn.close()
        return n > 0
    except sqlite3.DatabaseError:
        return False


def build() -> dict[str, Any]:
    """Extract every documented type/field/property into the cache."""
    started = time.time()
    conn = _db()
    conn.execute("PRAGMA journal_mode=OFF")
    conn.execute("PRAGMA synchronous=OFF")
    conn.execute("DELETE FROM docs")

    rows: list[tuple] = []
    files = 0
    for xml_path in PATHS.doc_xml_files():
        try:
            tree = ET.parse(xml_path)
        except ET.ParseError:
            continue
        members = tree.find("members")
        if members is None:
            continue
        files += 1
        for member in members.findall("member"):
            name = member.get("name") or ""
            if len(name) < 3 or name[1] != ":":
                continue
            kind, full = name[0], name[2:]
            if kind not in ("T", "F", "P") or _NOISE.search(full):
                continue
            summary = _text(member.find("summary"))
            if not summary:
                continue
            if kind == "T":
                owner, leaf = full, ""
            else:
                owner, _, leaf = full.rpartition(".")
            rows.append((name, owner, leaf, kind, summary))
            if len(rows) >= 5000:
                conn.executemany(
                    "INSERT OR REPLACE INTO docs (member,owner,leaf,kind,summary)"
                    " VALUES (?,?,?,?,?)", rows)
                rows.clear()

    if rows:
        conn.executemany(
            "INSERT OR REPLACE INTO docs (member,owner,leaf,kind,summary)"
            " VALUES (?,?,?,?,?)", rows)
    n = conn.execute("SELECT COUNT(*) n FROM docs").fetchone()["n"]
    conn.execute(
        "INSERT OR REPLACE INTO docmeta (key,value) VALUES ('built_at',?)",
        (str(int(time.time())),))
    conn.commit()
    conn.close()
    return {
        "xml_files": files,
        "documented_members": n,
        "seconds": round(time.time() - started, 1),
    }


def strip_bundle(type_name: str) -> str:
    """"Game2:Keen.Game2.X.Y" -> "Keen.Game2.X.Y"."""
    return type_name.split(":", 1)[1] if ":" in type_name else type_name


def type_doc(type_name: str) -> dict[str, Any]:
    """Documentation for a type and each of its documented fields."""
    full = strip_bundle(type_name)
    conn = _db()
    t = conn.execute(
        "SELECT summary FROM docs WHERE member=?", (f"T:{full}",)
    ).fetchone()
    fields = conn.execute(
        "SELECT leaf, kind, summary FROM docs WHERE owner=? AND kind IN ('F','P')"
        " ORDER BY leaf", (full,)
    ).fetchall()
    conn.close()
    return {
        "type": full,
        "summary": t["summary"] if t else None,
        "documented_fields": {r["leaf"]: r["summary"] for r in fields},
    }


def search_types(fragment: str, limit: int = 30) -> list[dict[str, str]]:
    conn = _db()
    rows = conn.execute(
        "SELECT member, summary FROM docs WHERE kind='T' AND member LIKE ?"
        " ORDER BY LENGTH(member) LIMIT ?", (f"%{fragment}%", limit)
    ).fetchall()
    conn.close()
    return [{"type": r["member"][2:], "summary": r["summary"]} for r in rows]
